'use strict';
const assert=require('node:assert/strict');
const d=require('../web/dashboard.js');
const body=(content,overrides={})=>({kind:'json',content,knownSizeBytes:5,truncated:false,omissionReason:null,summary:null,contentType:'application/json',...overrides});
const call=(id,overrides={})=>({id,state:'completed',durationMicros:12500,incompleteRequest:false,observedAt:'2026-11-06T00:00:00Z',endedAt:'2026-11-06T00:00:00.012500Z',revision:2,error:null,request:{method:'POST',url:'https://example.test/items?token=%5BREDACTED%5D',headers:{accept:['application/json']},body:body(false),startedAt:'2026-11-06T00:00:00Z',captureWarnings:[]},response:{statusCode:200,headers:{},body:body(false),endedAt:'2026-11-06T00:00:00.012500Z',captureWarnings:[]},...overrides});
const snapshot=calls=>({schemaVersion:2,sessionId:'s',version:4,clearGeneration:0,calls});
assert.equal(d.formatDuration(call('pending',{state:'pending',durationMicros:null})),'—');
assert.equal(d.formatCapturedSize(call('unknown',{response:{body:body(null,{knownSizeBytes:null})}})),'Unknown');
assert.equal(d.formatCapturedSize(call('zero',{response:{body:body('',{knownSizeBytes:0})}})),'0 B');
const state=snapshot([call('a')]),view=d.createViewState();d.pauseView(view,state);
state.calls=[call('b'),call('a')];state.version=5;
assert.deepEqual(d.visibleSnapshot(state,view).calls.map(c=>c.id),['a']);
assert.equal(d.waitingCount(state,view),1);
state.calls=[call('a')];assert.equal(d.waitingCount(state,view),0,'evicted waiting calls not counted');
d.invalidateView(view,state);assert.deepEqual(d.visibleSnapshot(state,view).calls,[]);
const omitted=call('omit');omitted.request.body=body('NEVER_EXPORT',{kind:'omitted',omissionReason:'policyOmitted'});
const truncated=call('truncate');truncated.response.body=body('NEVER_EXPORT',{kind:'text',truncated:true,omissionReason:'byteLimit'});
const summary=call('summary');summary.request.body=body('NEVER_EXPORT',{kind:'multipartSummary',summary:{fileCount:1,fieldCount:0,contentTypes:[]},knownSizeBytes:null});
const unmatched=call('unknown-start',{request:{...call('x').request,startedAt:null},incompleteRequest:true,durationMicros:null});
const pending=call('pending',{state:'pending',durationMicros:null});
const invalid=call('invalid',{request:{...call('x').request,url:'relative'}});
const all=[call('good'),omitted,truncated,summary,unmatched,pending,invalid];
const json=d.buildJsonExport(snapshot(all),all);
assert.equal(json._cote.capturePoint,'dio');assert.equal(json._cote.wireExact,false);assert.match(json._cote.comment,/not byte-exact/);
assert.equal(json.schemaVersion,2);assert.equal(json.calls.length,7);assert.ok(!JSON.stringify(json).includes('NEVER_EXPORT'));
assert.equal(json.calls[1].request.body.content,null);assert.equal(json.calls[2].response.body.content,null);
assert.equal(all[1].request.body.content,'NEVER_EXPORT','export never mutates captured state');
const result=d.buildHarExport(snapshot(all),all);
assert.equal(result.har.log.version,'1.2');assert.equal(result.har.log.entries.length,4);
assert.deepEqual(result.skipped.map(s=>s.id),['unknown-start','pending','invalid']);
assert.ok(!JSON.stringify(result.har).includes('NEVER_EXPORT'));
assert.equal(result.har.log.entries[0].time,12.5);
assert.equal(result.har.log.entries[0].request.postData.text,'false');
assert.equal(result.har.log.entries[0].response.content.text,'false');
assert.equal(Object.values(result.har.log.entries[0].timings).filter(value=>value>=0).reduce((a,b)=>a+b,0),12.5);
assert.match(result.har.log.entries[0].comment,/not measured TTFB/);
assert.equal(result.har.log.entries[0]._cote.observedDurationMicros,12500);
assert.equal(result.har.log.entries[0].response.bodySize,-1,'wire byte count unknown');
assert.equal(result.har.log.entries[1].request.postData,undefined);
assert.equal(result.har.log.entries[2].response.content.text,undefined);
assert.throws(()=>d.buildJsonExport(snapshot([]),[]),/No calls/);
assert.throws(()=>d.buildHarExport(snapshot([]),[]),/No calls/);
const fs=require('node:fs');fs.mkdirSync('/tmp/cote-v2-export-fixtures',{recursive:true});
fs.writeFileSync('/tmp/cote-v2-export-fixtures/sanitized.har',JSON.stringify(result.har,null,2));
fs.writeFileSync('/tmp/cote-v2-export-fixtures/sanitized.json',JSON.stringify(json,null,2));
console.log('dashboard duration, size, pause and export tests passed');
